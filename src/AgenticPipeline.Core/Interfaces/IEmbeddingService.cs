namespace AgenticPipeline.Core.Interfaces;

/// <summary>
/// Service interface for generating text embeddings using AI models
/// </summary>
public interface IEmbeddingService
{
    /// <summary>
    /// Generates an embedding vector for a single text input
    /// </summary>
    /// <param name="text">The text to generate embedding for</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>Embedding vector as float array</returns>
    Task<float[]> GenerateEmbeddingAsync(string text, CancellationToken cancellationToken = default);

    /// <summary>
    /// Generates embedding vectors for multiple text inputs in batch
    /// </summary>
    /// <param name="texts">List of texts to generate embeddings for</param>
    /// <param name="cancellationToken">Cancellation token</param>
    /// <returns>List of embedding vectors as float arrays</returns>
    Task<List<float[]>> GenerateEmbeddingsAsync(List<string> texts, CancellationToken cancellationToken = default);

    /// <summary>
    /// Gets the dimension size of the embeddings generated by this service
    /// </summary>
    int EmbeddingDimension { get; }
}
